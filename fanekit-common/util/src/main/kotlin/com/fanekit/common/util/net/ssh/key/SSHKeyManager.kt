    /**
     * 创建密码查找器
     */
    private fun createPasswordFinder(password: String): PasswordFinder {
        return object : PasswordFinder {
            override fun reqPassword(resource: net.schmizz.sshj.userauth.password.Resource<*>?): CharArray {
                return password.toCharArray()
            }

            override fun shouldRetry(resource: net.schmizz.sshj.userauth.password.Resource<*>?): Boolean {
                return false
            }
        }
    }

    /**
     * 保存密钥对到文件
     *
     * @param keyPairInfo 密钥对信息
     * @param privateKeyPath 私钥保存路径
     * @param publicKeyPath 公钥保存路径（可选）
     * @param password 私钥加密密码（可选）
     */
    fun saveKeyPairToFile(
        keyPairInfo: SSHKeyPairInfo,
        privateKeyPath: String,
        publicKeyPath: String? = null,
        password: String? = null
    ) {
        val privateKeyFile = File(privateKeyPath)
        privateKeyFile.parentFile?.mkdirs()

        // 保存私钥（简化实现，实际应该根据格式进行编码）
        val privateKeyContent = encodePrivateKey(keyPairInfo.keyPair, password)
        privateKeyFile.writeText(privateKeyContent)

        // 设置私钥文件权限（仅所有者可读写）
        privateKeyFile.setReadable(false, false)
        privateKeyFile.setReadable(true, true)
        privateKeyFile.setWritable(false, false)
        privateKeyFile.setWritable(true, true)

        // 保存公钥
        publicKeyPath?.let { path ->
            val publicKeyFile = File(path)
            val publicKeyContent = encodePublicKey(keyPairInfo.keyPair.public, keyPairInfo.comment)
            publicKeyFile.writeText(publicKeyContent)
        }
    }

    /**
     * 验证密钥对匹配性
     *
     * @param privateKeyPath 私钥文件路径
     * @param publicKeyPath 公钥文件路径
     * @param password 私钥密码（可选）
     * @return 是否匹配
     */
    fun validateKeyPair(
        privateKeyPath: String,
        publicKeyPath: String,
        password: String? = null
    ): Boolean {
        return try {
            val privateKey = loadKeyFromFile(privateKeyPath, password)
            val publicKeyContent = File(publicKeyPath).readText()
            val publicKey = parsePublicKey(publicKeyContent)

            // 简化的验证逻辑
            val privateFingerprint = generateFingerprint(privateKey.public)
            val publicFingerprint = generateFingerprint(publicKey)

            privateFingerprint == publicFingerprint
        } catch (e: Exception) {
            false
        }
    }

    /**
     * 获取密钥信息
     *
     * @param keyPath 密钥文件路径
     * @param password 密钥密码（可选）
     * @return 密钥信息
     */
    fun getKeyInfo(keyPath: String, password: String? = null): SSHKeyInfo {
        val keyProvider = loadKeyFromFile(keyPath, password)
        val publicKey = keyProvider.public

        return SSHKeyInfo(
            keyType = getKeyType(publicKey),
            keySize = getKeySize(publicKey),
            fingerprint = generateFingerprint(publicKey),
            comment = extractCommentFromPublicKey(keyPath + ".pub")
        )
    }

    /**
     * 生成密钥指纹
     */
    private fun generateFingerprint(publicKey: PublicKey): String {
        val encoded = publicKey.encoded
        val md5 = java.security.MessageDigest.getInstance("MD5")
        val digest = md5.digest(encoded)

        return digest.joinToString(":") {
            String.format("%02x", it)
        }
    }

    /**
     * 获取密钥类型
     */
    private fun getKeyType(publicKey: PublicKey): com.fanekit.common.util.net.ssh.key.SSHKeyType {
        return when (publicKey.algorithm) {
            "RSA" -> com.fanekit.common.util.net.ssh.key.SSHKeyType.RSA
            "DSA" -> com.fanekit.common.util.net.ssh.key.SSHKeyType.DSA
            "EC" -> com.fanekit.common.util.net.ssh.key.SSHKeyType.ECDSA
            "EdDSA" -> com.fanekit.common.util.net.ssh.key.SSHKeyType.Ed25519
            else -> com.fanekit.common.util.net.ssh.key.SSHKeyType.RSA
        }
    }

    /**
     * 获取密钥长度
     */
    private fun getKeySize(publicKey: PublicKey): Int {
        return when (publicKey) {
            is RSAPublicKey -> publicKey.modulus.bitLength()
            else -> 0
        }
    }

