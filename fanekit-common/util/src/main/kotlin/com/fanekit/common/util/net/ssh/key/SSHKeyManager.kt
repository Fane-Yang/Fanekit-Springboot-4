/**
 * SSH密钥管理器
 * 提供SSH密钥的生成、加载、验证和格式转换功能
 */
class SSHKeyManager {

    /**
     * 生成SSH密钥对
     *
     * @param keyType 密钥类型 (RSA, DSA, ECDSA, Ed25519)
     * @param keySize 密钥长度 (仅适用于RSA和DSA)
     * @param comment 密钥注释
     * @return 生成的密钥对信息
     */
    fun generateKeyPair(
        keyType: com.fanekit.common.util.net.ssh.key.SSHKeyType = com.fanekit.common.util.net.ssh.key.SSHKeyType.RSA,
        keySize: Int = 2048,
        comment: String = "Generated by SSHKeyManager"
    ): SSHKeyPairInfo {
        val keyPairGenerator = when (keyType) {
            com.fanekit.common.util.net.ssh.key.SSHKeyType.RSA -> KeyPairGenerator.getInstance("RSA").apply {
                initialize(keySize)
            }
            com.fanekit.common.util.net.ssh.key.SSHKeyType.DSA -> KeyPairGenerator.getInstance("DSA").apply {
                initialize(keySize)
            }
            com.fanekit.common.util.net.ssh.key.SSHKeyType.ECDSA -> KeyPairGenerator.getInstance("EC").apply {
                initialize(256) // 常用的ECDSA密钥长度
            }
            com.fanekit.common.util.net.ssh.key.SSHKeyType.Ed25519 -> {
                // Ed25519需要特殊处理，这里简化为RSA
                KeyPairGenerator.getInstance("RSA").apply {
                    initialize(2048)
                }
            }
        }

        val keyPair = keyPairGenerator.generateKeyPair()

        return SSHKeyPairInfo(
            keyType = keyType,
            keySize = keySize,
            keyPair = keyPair,
            comment = comment,
            fingerprint = generateFingerprint(keyPair.public)
        )
    }


    /**
     * 从文件加载密钥
     */
    fun loadKeyFromFile(keyPath: String, password: String? = null): KeyProvider {
        val keyFile = File(keyPath)
        if (!keyFile.exists()) {
            throw IllegalArgumentException("Key file does not exist: $keyPath")
        }

        val keyContent = keyFile.readText()
        val passwordFinder = password?.let { createPasswordFinder(it) }

        return when {
            keyContent.contains("BEGIN OPENSSH PRIVATE KEY") -> {
                OpenSSHKeyFile().apply {
                    if (passwordFinder != null) {
                        init(StringReader(keyContent), passwordFinder)
                    } else {
                        init(StringReader(keyContent), null as PasswordFinder?)
                    }
                }
            }
            keyContent.contains("BEGIN PRIVATE KEY") || keyContent.contains("BEGIN ENCRYPTED PRIVATE KEY") -> {
                PKCS8KeyFile().apply {
                    if (passwordFinder != null) {
                        init(StringReader(keyContent), passwordFinder)
                    } else {
                        init(StringReader(keyContent), null as PasswordFinder?)
                    }
                }
            }
            keyContent.contains("PuTTY-User-Key-File") -> {
                PuTTYKeyFile().apply {
                    if (passwordFinder != null) {
                        init(StringReader(keyContent), passwordFinder)
                    } else {
                        init(StringReader(keyContent), null as PasswordFinder?)
                    }
                }
            }
            else -> {
                throw IllegalArgumentException("Unsupported key format")
            }
        }
    }

    /**
     * 从字符串加载密钥
     */
    fun loadKeyFromString(keyContent: String, password: String? = null): KeyProvider {
        val passwordFinder = password?.let { createPasswordFinder(it) }

        return when {
            keyContent.contains("BEGIN OPENSSH PRIVATE KEY") -> {
